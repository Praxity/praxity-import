test("imports a Lectora publish: title order, chapters, template chrome, reading order, hidden reveals, questions and a test group", async () => {
	const root = lectoraPackage();
	const course = extractLectora(root);
	assert.equal(course.toolVersion, "Lectora Online v 6.2.4(242)");
	assert.equal(course.title, "Harbour Basics");
	assert.equal(course.description, "Learn the harbour.");
	assert.equal(course.locale, "en");
	assert.deepEqual(course.lessons.map((l) => l.title), ["Chapter 1", "Test 1"]);
	assert.deepEqual(course.lessons.map((l) => l.pages.map((p) => p.title)), [["START HERE", "REVEAL"], ["Test 1", "PRACTICE ROUND"]]);
	assert.ok(course.sourceText.includes("Hidden reveal text"), "hidden text is inventoried");
	assert.ok(course.sourceText.includes("Not quite, look again."), "action-driven feedback is inventoried");
	assert.ok(course.sourceText.includes("Yes, it does."), "test choice feedback is inventoried");
	assert.ok(course.sourceText.includes("Tab 1"), "non-navigation button labels are inventoried");
	assert.ok(!course.sourceText.includes("SKIP") && !course.sourceText.includes("BEGIN"), "template chrome and navigation are not");

	const out = join(tmp(), "course");
	const report = await importPackage(root, out);
	assert.equal(report.detected.tool, "lectora");
	const first = readFileSync(join(out, report.lessons[0]?.file ?? ""), "utf8");
	assert.match(first, /^# START HERE\n\n## Check the \*\*main\*\* valve\.\n\n\/assets\/images\/lion\.png\nalt: A lion resting\n\nSide note\n\n--- REVEAL\n\n- Gloves\n- Boots\n\nVisible after the tab\n\nHidden reveal text$/m);
	assert.doesNotMatch(first, /SKIP|Acme Harbour|logo\.png|BEGIN|“/);
	const second = readFileSync(join(out, report.lessons[1]?.file ?? ""), "utf8");
	assert.match(second, /^# Test 1\nas: assessment-group\nshowResultsSummary: true\npassingScore: 70\n\n\*\*1\/2 \| MULTIPLE CHOICE\*\*\n\n## Which animal \*roars\*\?\nas: choice\nscored: true\n\n\(x\) Lion\nfeedback: Yes, it does\.\n\( \) Mouse\nfeedback: No, it squeaks\.\n\nGreat work!\n\n## The king of the jungle is the \S+\.\nas: fill-blank\nscored: true\n\n\{lion\}\n\nclose: assessment-group$/m);
	assert.match(second, /^--- PRACTICE ROUND\n\n## How many lions\?\nas: choice\n\n\( \) One\n\(x\) Two\n\nYour score: %$/m);
	const sources = report.losses.map((l) => `${l.source}/${l.effect}`);
	assert.ok(sources.includes("lectora:theme/approximated"), "chrome recorded in theme loss");
	assert.ok(report.losses.some((l) => l.source === "lectora:action" && l.at === "page4" && l.detail.includes("Tab 1")), "reveal button recorded");
	assert.ok(sources.includes("lectora:hidden/approximated"), "hidden objects recorded");
	assert.ok(sources.includes("lectora:test/approximated"), "merged test pages recorded");
	assert.ok(report.losses.some((l) => l.source === "lectora:variable" && l.detail.includes("Test_1_Score")), "runtime variable recorded");
});

test("Lectora maps page fonts, inline colours and explicitly marked repeated branding", async () => {
	const root = tmp();
	files(root, {
		"trivantis.js": "",
		"trivantisPage.css": 'body {background-color:#eee;font-family:Verdana;color:#999} .ttxt {color:black} /* .ttxt {color:red} */',
		"images/brand.png": "brand",
	});
	for (let i = 1; i <= 3; i++) {
		const spec = page(`page${i}`, {
			title: `Page ${i}`, idx: i, next: "", decl: [["text1", "jsWndText"], ["text2", "jsWndText"], ["shape3", "jsWndShape"], ["image4", "jsWndImage"], ["shape5", "jsWndShape"]],
			order: ["text1", "text2", "shape3", "image4"], objects: {
				text1: { html: txt(`<p style="color:rgb(17, 34, 51)">Body ${i}</p>`) },
				text2: { html: txt(`<h1><span style="font-family: &quot;Lato&quot;, sans-serif">Heading ${i}</span></h1>`) },
				shape3: { html: '<svg><path style="fill: rgb(18, 52, 86);"></path></svg>', cw: '{name:"Header_Background"}', data: { bHideFromScrRdr: true } },
				image4: { html: '<img src="images/brand.png" alt="Brand">', cw: '{name:"Company Logo"}', data: { bHideFromScrRdr: true } },
				shape5: { html: `<svg id="background${i}"><path style="fill: #fefefe;"></path></svg>`, cw: '{name:"Background_Color"}', data: { bHideFromScrRdr: true } },
			},
		});
		spec[`page${i}.html`] = spec[`page${i}.html`]?.replace("</head>", '<link rel="stylesheet" href="trivantisPage.css"><style>@media print {body {color:#f00}} .ttxt {font-family:Inter}</style></head>') ?? "";
		spec[`device_Desktop/page${i}.js`] = spec[`device_Desktop/page${i}.js`]?.replace('focusColor:', 'font:{name:"Open Sans",color:null},\nfocusColor:') + '\nrcdObj.backgrd_Desktop = ["#fafafa","",0,0,1];';
		files(root, spec);
	}
	const course = extractLectora(root);
	assert.deepEqual(course.theme, { density: "compact", blockSpacing: "compact", navigation: "slides", background: "#fefefe", bodyFont: "Open Sans", headingFont: "Lato", text: "#112233", accent: "#123456", logo: "images/brand.png" });
	assert.equal(course.losses.filter((l) => l.source === "lectora:theme" && l.effect === "approximated").length, 1);
	const out = join(tmp(), "course");
	await importPackage(root, out);
	const yaml = readFileSync(join(out, "course.yaml"), "utf8");
	assert.match(yaml, /colorAccent: "#123456"/);
	assert.match(yaml, /logoUrl: \/assets\/images\/brand.png/);
	assert.equal(readFileSync(join(out, "assets/images/brand.png"), "utf8"), "brand");
});

test("Lectora ignores unmarked image filenames and outside stylesheets; font ties use name order", () => {
	const root = lectoraPackage();
	assert.equal(extractLectora(root).theme?.logo, undefined, "logo.png is not an authored logo designation");
	const outside = join(tmp(), "outside.css");
	writeFileSync(outside, '.ttxt{font-family:"Outside Font";color:#123456}');
	symlinkSync(outside, join(root, "linked.css"));
	const html = readFileSync(join(root, "page1.html"), "utf8");
	writeFileSync(join(root, "page1.html"), html.replace("</head>", '<link rel="stylesheet" href="linked.css"></head>'));
	const js = readFileSync(join(root, "device_Desktop/page1.js"), "utf8");
	writeFileSync(join(root, "device_Desktop/page1.js"), js.replace('Check the ', '<span style=\\"font-family:Verdana\\">BBBB</span><span style=\\"font-family:Inter\\">AAAA</span>Check the '));
	assert.equal(extractLectora(root).theme?.headingFont, "Inter");
	assert.notEqual(extractLectora(root).theme?.bodyFont, "Outside Font");
});

